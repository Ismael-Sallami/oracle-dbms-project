-- 1. Borrado previo (Orden inverso para romper dependencias)
BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
        'CONTIENE_HASHTAG', 'AMISTAD', 'BLOQUEO', 'ARCHIVADO', 'ME_GUSTA',
        'CONVERSA', 'MENSAJE', 'ANUNCIO', 'PUBLICACION', 'HASHTAG', 'USUARIO'
    )) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS';
    END LOOP;
END;
/

-- =============================================================================
-- TABLAS PRINCIPALES (Entidades Fuertes)
-- =============================================================================

-- 1. TABLA USUARIO
CREATE TABLE USUARIO (
    IDUSUARIO           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBREUSUARIO       VARCHAR2(20) NOT NULL,
    EMAIL               VARCHAR2(50) NOT NULL,
    CONTRASENIA         VARCHAR2(20) NOT NULL,
    IMAGENDEPERFIL      VARCHAR2(255),
    BIOGRAFIA           VARCHAR2(100),
    FECHAMODIFICACION   DATE,
    FECHAELIMINACION    DATE,
    
    CONSTRAINT PK_USUARIO PRIMARY KEY (IDUSUARIO),
    CONSTRAINT UK_USUARIO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT UK_USUARIO_NOMBRE UNIQUE (NOMBREUSUARIO)
);

-- 2. TABLA ANUNCIO
CREATE TABLE ANUNCIO (
    IDANUNCIO           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    TITULO              VARCHAR2(100) NOT NULL,
    CUERPO              VARCHAR2(255),
    ENLACE              VARCHAR2(255) NOT NULL,
    FECHAINICIO         DATE DEFAULT SYSDATE,
    FECHAFIN            DATE,
    ESTADO              VARCHAR2(1) DEFAULT 'Y' CHECK (ESTADO IN ('Y', 'N')),
    
    CONSTRAINT PK_ANUNCIO PRIMARY KEY (IDANUNCIO)
);

-- 3. TABLA PUBLICACION
CREATE TABLE PUBLICACION (
    IDPUBLICACION       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOMBRE              VARCHAR2(20) NOT NULL,
    DESCRIPCION         VARCHAR2(80),
    CATEGORIA           VARCHAR2(32),
    IMAGEN              VARCHAR2(255),
    FECHACREACION       DATE DEFAULT SYSDATE,
    FECHAMODIFICACION   DATE,
    ELIMINADO           VARCHAR2(1) DEFAULT 'N' CHECK (ELIMINADO IN ('Y', 'N')),
    IDUSUARIO           NUMBER NOT NULL,
    IDANUNCIO           NUMBER,

    CONSTRAINT PK_PUBLICACION PRIMARY KEY (IDPUBLICACION),
    CONSTRAINT FK_PUB_USUARIO FOREIGN KEY (IDUSUARIO) REFERENCES USUARIO(IDUSUARIO) ON DELETE CASCADE,
    CONSTRAINT FK_PUB_ANUNCIO FOREIGN KEY (IDANUNCIO) REFERENCES ANUNCIO(IDANUNCIO) ON DELETE SET NULL
);

-- 6. TABLA HASHTAG (Necesaria para la tabla 13)
CREATE TABLE HASHTAG (
    HASHTAG             VARCHAR2(32) NOT NULL,
    MENCIONES           NUMBER DEFAULT 0,
    CATEGORIA           VARCHAR2(32),
    
    CONSTRAINT PK_HASHTAG PRIMARY KEY (HASHTAG)
);

-- TABLA MENSAJE (Base para mensajería)
CREATE TABLE MENSAJE (
    IDMENSAJE           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    IDUSUARIO1          NUMBER NOT NULL, -- Emisor
    IDUSUARIO2          NUMBER NOT NULL, -- Receptor
    MENSAJE             VARCHAR2(100),
    FECHAENVIO          DATE DEFAULT SYSDATE,
    BITVISTO            VARCHAR2(1) DEFAULT 'N',
    
    CONSTRAINT PK_MENSAJE PRIMARY KEY (IDMENSAJE),
    CONSTRAINT FK_MSG_U1 FOREIGN KEY (IDUSUARIO1) REFERENCES USUARIO(IDUSUARIO) ON DELETE CASCADE,
    CONSTRAINT FK_MSG_U2 FOREIGN KEY (IDUSUARIO2) REFERENCES USUARIO(IDUSUARIO) ON DELETE CASCADE
);

-- =============================================================================
-- TABLAS DE RELACIÓN (Según tu LaTeX)
