-- 9. BLOQUEAR_USUARIO (BLOQUEO)
CREATE TABLE BLOQUEO (
    IDUSUARIO1          NUMBER NOT NULL,
    IDUSUARIO2          NUMBER NOT NULL,
    FECHABLOQUEO        DATE DEFAULT SYSDATE NOT NULL,
    
    CONSTRAINT PK_BLOQUEO PRIMARY KEY (IDUSUARIO1, IDUSUARIO2),
    CONSTRAINT FK_BLOQ_U1 FOREIGN KEY (IDUSUARIO1) REFERENCES USUARIO(IDUSUARIO) ON DELETE CASCADE,
    CONSTRAINT FK_BLOQ_U2 FOREIGN KEY (IDUSUARIO2) REFERENCES USUARIO(IDUSUARIO) ON DELETE CASCADE,
    CONSTRAINT CK_BLOQ_DISTINTOS CHECK (IDUSUARIO1 <> IDUSUARIO2)
