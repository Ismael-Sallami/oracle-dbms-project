-- 7. LIKE (ME_GUSTA)
-- \pk{\overwithlabel{idUsuario}{CE1}, \overwithlabel{idPublicacion}{CE3}}
CREATE TABLE ME_GUSTA (
    IDUSUARIO           NUMBER NOT NULL,
    IDPUBLICACION       NUMBER NOT NULL,
    FECHA               DATE DEFAULT SYSDATE,
    
    CONSTRAINT PK_ME_GUSTA PRIMARY KEY (IDUSUARIO, IDPUBLICACION),
    CONSTRAINT FK_LIKE_USUARIO FOREIGN KEY (IDUSUARIO) REFERENCES USUARIO(IDUSUARIO) ON DELETE CASCADE,
    CONSTRAINT FK_LIKE_PUB FOREIGN KEY (IDPUBLICACION) REFERENCES PUBLICACION(IDPUBLICACION) ON DELETE CASCADE
);

-- 8. DES/ARCHIVAR (ARCHIVADO)
-- \pk{\overwithlabel{idUsuario1}{CE1}, \overwithlabel{idUsuario2}{CE1}}
CREATE TABLE ARCHIVADO (
    IDUSUARIO1          NUMBER NOT NULL, -- Quien archiva
    IDUSUARIO2          NUMBER NOT NULL, -- Chat archivado
    FECHA               DATE DEFAULT SYSDATE,
    
    CONSTRAINT PK_ARCHIVADO PRIMARY KEY (IDUSUARIO1, IDUSUARIO2),
    CONSTRAINT FK_ARCH_U1 FOREIGN KEY (IDUSUARIO1) REFERENCES USUARIO(IDUSUARIO) ON DELETE CASCADE,
    CONSTRAINT FK_ARCH_U2 FOREIGN KEY (IDUSUARIO2) REFERENCES USUARIO(IDUSUARIO) ON DELETE CASCADE
);

-- 9. BLOQUEAR_USUARIO (BLOQUEO)
-- \pk{\overwithlabel{idUsuario1}{CE1},\overwithlabel{idUsuario2}{CE1}}, fechaBloqueo
CREATE TABLE BLOQUEO (
    IDUSUARIO1          NUMBER NOT NULL, -- Bloqueador
    IDUSUARIO2          NUMBER NOT NULL, -- Bloqueado
    FECHABLOQUEO        DATE DEFAULT SYSDATE NOT NULL,
    
    CONSTRAINT PK_BLOQUEO PRIMARY KEY (IDUSUARIO1, IDUSUARIO2),
    CONSTRAINT FK_BLOQ_U1 FOREIGN KEY (IDUSUARIO1) REFERENCES USUARIO(IDUSUARIO) ON DELETE CASCADE,
    CONSTRAINT FK_BLOQ_U2 FOREIGN KEY (IDUSUARIO2) REFERENCES USUARIO(IDUSUARIO) ON DELETE CASCADE,
    CONSTRAINT CK_BLOQ_DISTINTOS CHECK (IDUSUARIO1 <> IDUSUARIO2)
);

-- 10. AÑADIR_AMIGO (AMISTAD)
-- \pk{\overwithlabel{idUsuario1}{CE1}, \overwithlabel{idUsuario2}{CE1}}, fechaAmistad
CREATE TABLE AMISTAD (
    IDUSUARIO1          NUMBER NOT NULL, -- Solicitante
    IDUSUARIO2          NUMBER NOT NULL, -- Receptor
    FECHAAMISTAD        DATE DEFAULT SYSDATE NOT NULL,
    ESTADO              VARCHAR2(20) DEFAULT 'ACEPTADA',
    
    CONSTRAINT PK_AMISTAD PRIMARY KEY (IDUSUARIO1, IDUSUARIO2),
    CONSTRAINT FK_AMIST_U1 FOREIGN KEY (IDUSUARIO1) REFERENCES USUARIO(IDUSUARIO) ON DELETE CASCADE,
    CONSTRAINT FK_AMIST_U2 FOREIGN KEY (IDUSUARIO2) REFERENCES USUARIO(IDUSUARIO) ON DELETE CASCADE,
    CONSTRAINT CK_AMIST_DISTINTOS CHECK (IDUSUARIO1 <> IDUSUARIO2)
);

-- 13. CREAR_O_MENCIONAR_HASHTAG (CONTIENE_HASHTAG)
-- \pk{\overwithlabel{idPublicacion}{CE3}, \overwithlabel{hashtag}{CE2}}
CREATE TABLE CONTIENE_HASHTAG (
    IDPUBLICACION       NUMBER NOT NULL,
    HASHTAG           VARCHAR2(32) NOT NULL,
    
    CONSTRAINT PK_CONTIENE_HASHTAG PRIMARY KEY (IDPUBLICACION, HASHTAG),
    CONSTRAINT FK_CH_PUB FOREIGN KEY (IDPUBLICACION) REFERENCES PUBLICACION(IDPUBLICACION) ON DELETE CASCADE,
    CONSTRAINT FK_CH_TAG FOREIGN KEY (HASHTAG) REFERENCES HASHTAG(HASHTAG) ON DELETE CASCADE
);

-- Tabla auxiliar para que APEX funcione (si se usaba en LOVs de mensajes)
CREATE TABLE CONVERSA (
    IDCONVERSA          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    IDUSUARIO1          NUMBER NOT NULL,
    IDUSUARIO2          NUMBER NOT NULL,
    FECHAINICIO         DATE DEFAULT SYSDATE,
    CONSTRAINT PK_CONVERSA PRIMARY KEY (IDCONVERSA),
    CONSTRAINT FK_CONV_U1 FOREIGN KEY (IDUSUARIO1) REFERENCES USUARIO(IDUSUARIO) ON DELETE CASCADE,
    CONSTRAINT FK_CONV_U2 FOREIGN KEY (IDUSUARIO2) REFERENCES USUARIO(IDUSUARIO) ON DELETE CASCADE
);

